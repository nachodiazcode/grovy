  private async callGeminiApi(prompt: string, origin: Point): Promise<FigmaElement[]> {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${this.settings().model}:generateContent?key=${this.settings().apiKey}`;

    const systemInstruction = `You are an expert UI/UX designer and vector generator.
Given a user prompt, output a JSON array of FigmaElement objects describing a complete UI component or screen.
Every element must have valid x, y, width, height, type (frame, rect, circle, text, star, line), fill, stroke, cornerRadius, etc.
Origin top-left is around x=${origin.x}, y=${origin.y}.
Return ONLY valid JSON matching Array<FigmaElement>.`;

    const res = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{ parts: [{ text: `${systemInstruction}\n\nUser Prompt: ${prompt}` }] }],
        generationConfig: { responseMimeType: 'application/json' },
      }),
    });

    if (!res.ok) {
      throw new Error(`Gemini API error: ${res.statusText}`);
    }

    const data = await res.json();
    const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;
    if (text) {
      const parsed = JSON.parse(text);
      if (Array.isArray(parsed)) {
        return parsed;
      }
    }
    return [];
  }
