  readonly settings = signal<AISettings>({
    apiKey: localStorage.getItem('grovy_gemini_api_key') || '',
    model: 'gemini-2.5-flash',
    useGemini: !!localStorage.getItem('grovy_gemini_api_key'),
  });

  readonly isGenerating = signal<boolean>(false);

  setApiKey(key: string) {
    this.settings.update((s) => ({ ...s, apiKey: key, useGemini: !!key }));
    localStorage.setItem('grovy_gemini_api_key', key);
  }

  async generateUIFromPrompt(prompt: string, atPoint: Point = { x: 780, y: 80 }): Promise<FigmaElement[]> {
    this.isGenerating.set(true);

    try {
      // Small simulated latency for UX feedback
      await new Promise((r) => setTimeout(r, 600));

      const lower = prompt.toLowerCase();

      // Check if Gemini API key is configured
      if (this.settings().useGemini && this.settings().apiKey) {
        try {
          const geminiElements = await this.callGeminiApi(prompt, atPoint);
          if (geminiElements && geminiElements.length > 0) {
            return geminiElements;
          }
        } catch (e) {
          console.warn('Gemini API call failed, falling back to smart local generator', e);
        }
      }

      // Smart semantic local generator
      return this.generateSmartLocalTemplate(lower, atPoint);
    } finally {
      this.isGenerating.set(false);
    }
  }

