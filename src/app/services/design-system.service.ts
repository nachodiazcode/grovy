@Injectable({
  providedIn: 'root',
})
export class DesignSystemService {
  readonly colorTokens = signal<ColorToken[]>(DEFAULT_COLOR_TOKENS);
  readonly typographyTokens = signal<TypographyToken[]>(DEFAULT_TYPO_TOKENS);
  readonly components = signal<ComponentPreset[]>(DEFAULT_PRESETS);

  addColorToken(name: string, hex: string, category: 'brand' | 'neutral' | 'semantic' = 'brand') {
    const token: ColorToken = {
      id: 'color-' + Date.now(),
      name,
      hex,
      category,
    };
    this.colorTokens.update((prev) => [...prev, token]);
  }

  saveSelectionAsComponent(name: string, description: string, elements: FigmaElement[]) {
    if (elements.length === 0) return;

    // Normalize coordinates so the component top-left is (0, 0)
    let minX = Infinity;
    let minY = Infinity;
    for (const el of elements) {
      if (el.x < minX) minX = el.x;
      if (el.y < minY) minY = el.y;
    }

    const normalizedElements: FigmaElement[] = elements.map((el) => ({
      ...JSON.parse(JSON.stringify(el)),
      x: el.x - minX,
      y: el.y - minY,
    }));

    const preset: ComponentPreset = {
      id: 'custom-comp-' + Date.now(),
      name: name.trim() || 'Nuevo Componente',
      category: 'Custom',
      description: description.trim() || 'Componente personalizado del usuario',
      elements: normalizedElements,
    };

    this.components.update((prev) => [preset, ...prev]);
  }
}
